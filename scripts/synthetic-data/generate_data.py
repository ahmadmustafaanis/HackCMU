def weighted_choice(rng: random.Random, items):
    """Pick one item from a list of dicts with a 'weight' key."""
    weights = [it["weight"] for it in items]
    return rng.choices(items, weights=weights, k=1)[0]


def jittered_point(rng: random.Random, hotspot):
    """
    Return a GeoJSON Point near `hotspot`, using Gaussian jitter
    (random.gauss) instead of uniform noise, so density falls off
    naturally from the hotspot center.
    """
    lat = hotspot["lat"] + rng.gauss(0, JITTER_SIGMA_DEG)
    lng = hotspot["lng"] + rng.gauss(0, JITTER_SIGMA_DEG)
    # Clamp to sane bounds (safety net; jitter sigma is small so this
    # essentially never triggers).
    lat = max(-90.0, min(90.0, lat))
    lng = max(-180.0, min(180.0, lng))
    return {"type": "Point", "coordinates": [round(lng, 6), round(lat, 6)]}


def random_name(rng: random.Random):
    return f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}"


def name_to_email(name: str, dedupe_suffix: int | None = None):
    local = name.lower().replace(" ", ".")
    if dedupe_suffix is not None:
        local = f"{local}{dedupe_suffix}"
    return f"{local}@andrew.cmu.edu"


def random_created_at(rng: random.Random, now: datetime):
    """ISO 8601 timestamp spread over roughly the last 30 days."""
    seconds_back = rng.uniform(0, 30 * 24 * 3600)
    ts = now - timedelta(seconds=seconds_back)
    return ts.isoformat().replace("+00:00", "Z")


def make_bio(rng: random.Random, interests):
    template = rng.choice(BIO_TEMPLATES)
    kw0 = rng.choice(interests)
    kw1 = rng.choice(interests)
    return template.format(kw0=kw0, kw1=kw1)


def make_raw_text(rng: random.Random, keywords):
    template = rng.choice(RAW_TEXT_TEMPLATES)
    # Figure out how many distinct {kwN} slots this template needs.
    needed = sum(1 for tag in ("{kw0}", "{kw1}", "{kw2}", "{kw3}") if tag in template)
    needed = max(needed, 1)
    pool = list(keywords)
    while len(pool) < needed:
        pool.append(rng.choice(keywords))
    chosen = rng.sample(pool, needed) if len(pool) >= needed else pool
    slots = {f"kw{i}": chosen[i] for i in range(needed)}
    # Fill any unused slot names defensively (shouldn't be needed given
    # `needed` computation above, but keeps .format() from KeyError-ing
    # if a template is edited later without updating slot counts).
    for i in range(4):
        slots.setdefault(f"kw{i}", rng.choice(keywords))
    return template.format(**slots)


def generate_users(rng: random.Random, count: int, now: datetime):
    users = []
    seen_emails = Counter()
    for _ in range(count):
        name = random_name(rng)
        base_email = name_to_email(name)
        seen_emails[base_email] += 1
        email = base_email if seen_emails[base_email] == 1 else name_to_email(
            name, seen_emails[base_email]
        )

        hotspot = weighted_choice(rng, HOTSPOTS)
        location = jittered_point(rng, hotspot)

        n_interests = rng.randint(3, 6)
        interests = rng.sample(INTEREST_VOCAB, n_interests)

        user = {
            "_id": str(uuid.uuid4()),
            "name": name,
            "email": email,
            "location": location,
            "interests": interests,
            "bio": make_bio(rng, interests),
            "availability": rng.choice(AVAILABILITY_OPTIONS),
            "age_range": rng.choice(AGE_RANGES),
            "created_at": random_created_at(rng, now),
            "_hotspot": hotspot["name"],  # internal, stripped before output
        }
        users.append(user)
    return users


def generate_activities(rng: random.Random, count: int, users, now: datetime):
    activities = []
    hotspot_by_name = {h["name"]: h for h in HOTSPOTS}
    for _ in range(count):
        creator = rng.choice(users)
        creator_hotspot = hotspot_by_name[creator["_hotspot"]]

        n_keywords = rng.randint(2, 4)
        keywords = rng.sample(INTEREST_VOCAB, n_keywords)

        # Activity location is near the creator's own location: jitter
        # again around the same hotspot the creator belongs to.
        location = jittered_point(rng, creator_hotspot)
        start = now + timedelta(minutes=rng.randint(0, 24 * 60))
        duration = ACTIVITY_DURATIONS_MINUTES.get(keywords[0], 60)

        activity = {
            "_id": str(uuid.uuid4()),
            "creator_id": creator["_id"],
            "raw_text": make_raw_text(rng, keywords),
            "keywords": keywords,
            "location": location,
            "status": rng.choices(ACTIVITY_STATUSES, weights=ACTIVITY_STATUS_WEIGHTS, k=1)[0],
            "availability": rng.choice(AVAILABILITY_OPTIONS),
            "created_at": random_created_at(rng, now),
            "start_time": start.isoformat().replace("+00:00", "Z"),
            "duration_minutes": duration,
        }
        activities.append(activity)
    return activities


def strip_internal_fields(docs):
    """Return copies of docs with any leading-underscore-prefixed
    scratch keys (except _id) removed, for output."""
    cleaned = []
    for doc in docs:
        cleaned.append({k: v for k, v in doc.items() if k == "_id" or not k.startswith("_")})
    return cleaned


def write_jsonl(path: Path, docs):
    with path.open("w") as f:
        for doc in docs:
            f.write(json.dumps(doc, ensure_ascii=False))
            f.write("\n")


def write_pretty_json(path: Path, docs):
    with path.open("w") as f:
        json.dump(docs, f, ensure_ascii=False, indent=2)
        f.write("\n")


def summarize_hotspot_distribution(users):
    counts = Counter(u["_hotspot"] for u in users)
    total = len(users)
    lines = []
    for h in HOTSPOTS:
        name = h["name"]
        n = counts.get(name, 0)
        pct = (n / total * 100) if total else 0
        lines.append(f"    {name:<22} {n:>6}  ({pct:5.1f}%)")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Generate synthetic MongoDB dataset for a campus "
        "social / activity-matching app."
    )
    parser.add_argument("--users", type=int, default=1000, help="number of user docs to generate (default: 1000)")
    parser.add_argument("--activities", type=int, default=400, help="number of activity docs to generate (default: 400)")
    parser.add_argument("--seed", type=int, default=None, help="random seed for reproducible output (default: unseeded)")
    parser.add_argument(
        "--out-dir",
        type=str,
        default=None,
        help="output directory (default: ./output next to this script)",
    )
    args = parser.parse_args()

    rng = random.Random(args.seed)
    now = datetime.now(timezone.utc)

    script_dir = Path(__file__).resolve().parent
    out_dir = Path(args.out_dir).resolve() if args.out_dir else script_dir / "output"
    out_dir.mkdir(parents=True, exist_ok=True)

    users = generate_users(rng, args.users, now)
    activities = generate_activities(rng, args.activities, users, now)

    users_out = strip_internal_fields(users)
    activities_out = strip_internal_fields(activities)

    write_jsonl(out_dir / "users.json", users_out)
    write_jsonl(out_dir / "activities.json", activities_out)
    write_pretty_json(out_dir / "users.pretty.json", users_out)
    write_pretty_json(out_dir / "activities.pretty.json", activities_out)

    status_counts = Counter(a["status"] for a in activities_out)

    print("Synthetic data generation complete.")
    print(f"  users:      {len(users_out):>6}  -> {out_dir / 'users.json'}")
    print(f"  activities: {len(activities_out):>6}  -> {out_dir / 'activities.json'}")
    print()
    print("Hotspot distribution (users):")
    print(summarize_hotspot_distribution(users))
    print()
    print("Activity status distribution:")
    for status in ACTIVITY_STATUSES:
        n = status_counts.get(status, 0)
        pct = (n / len(activities_out) * 100) if activities_out else 0
        print(f"    {status:<10} {n:>6}  ({pct:5.1f}%)")
    print()
    print("Output files:")
    for fname in ("users.json", "activities.json", "users.pretty.json", "activities.pretty.json"):
        fpath = out_dir / fname
        size = fpath.stat().st_size
        print(f"    {fpath}  ({size:,} bytes)")


if __name__ == "__main__":
    main()
