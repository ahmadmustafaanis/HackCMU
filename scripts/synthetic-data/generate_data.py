#!/usr/bin/env python3
"""
generate_data.py - Synthetic MongoDB dataset generator for a campus
social / activity-matching app (HackCMU project).

Generates two collections:
  - users:      people with a home location, interests, bio, availability
  - activities: user-posted "let's do X" activities with ground-truth
                 keyword labels and a location near their creator

Design goals:
  - Zero external dependencies (Python stdlib only: random, json, math,
    argparse, datetime, pathlib, uuid, collections).
  - Locations cluster around 5 weighted Pittsburgh hotspots using
    Gaussian jitter (random.gauss), NOT uniform noise, so a heatmap
    over this data shows realistic hot/cold zones.
  - A fixed vocabulary of ~30 interest/activity tags is shared between
    users.interests and activities.keywords so overlap is meaningful
    and testable (e.g. for matching / recommendation algorithms).
  - activities.raw_text is generated by filling varied sentence
    templates with the activity's keywords, so it reads like a real
    user post -- useful for testing an LLM-based keyword extractor
    against the known-good activities.keywords ground truth.

Usage:
    python3 generate_data.py --users 1000 --activities 400
    python3 generate_data.py --users 5000 --activities 2000 --seed 42

Output (written to ./output/ relative to this script):
    users.json           JSONL, one user doc per line (mongoimport-ready)
    activities.json      JSONL, one activity doc per line (mongoimport-ready)
    users.pretty.json     indented JSON array, for humans
    activities.pretty.json indented JSON array, for humans
"""

